import type { PerspectiveMatch } from "./match";
import type { RivalrySummary } from "./stats";
import type { PlayerKey, PlayerPair } from "./types";

export interface Insight {
  id: string;
  /** Translation key (ins.*) and parameters. */
  key: "ins.lead" | "ins.level" | "ins.recent" | "ins.streak" | "ins.accuracy" | "ins.possession" | "ins.cleanSheets" | "ins.goals";
  params: Record<string, string | number>;
  tone: PlayerKey | "neutral";
}

const fmt = (n: number) => (Number.isInteger(n) ? String(n) : n.toFixed(1));

/**
 * Short, factual observations derived from calculated statistics. Every
 * sentence is backed by a number in `summary`; nothing is generated by AI.
 */
export function buildInsights(
  summary: RivalrySummary,
  matches: readonly PerspectiveMatch[],
  pair: PlayerPair,
): Insight[] {
  const out: Insight[] = [];
  const name = (k: PlayerKey) => pair[k].display_name;
  const { a, b } = summary;
  if (summary.totalMatches === 0) return out;

  if (a.wins !== b.wins) {
    const lead: PlayerKey = a.wins > b.wins ? "a" : "b";
    out.push({
      id: "lead",
      tone: lead,
      key: "ins.lead",
      params: { name: name(lead), w: Math.max(a.wins, b.wins), l: Math.min(a.wins, b.wins) },
    });
  } else {
    out.push({ id: "lead", tone: "neutral", key: "ins.level", params: { n: a.wins } });
  }

  const window = Math.min(10, matches.length);
  if (window >= 5) {
    const recent = matches.slice(-window);
    const winsA = recent.filter((pm) => pm.winner === "a").length;
    const winsB = recent.filter((pm) => pm.winner === "b").length;
    if (winsA !== winsB) {
      const k: PlayerKey = winsA > winsB ? "a" : "b";
      out.push({
        id: "recent",
        tone: k,
        key: "ins.recent",
        params: { name: name(k), w: Math.max(winsA, winsB), n: window },
      });
    }
  }

  const streak = summary.currentStreak;
  if (streak.holder && streak.length >= 2) {
    out.push({
      id: "streak",
      tone: streak.holder,
      key: "ins.streak",
      params: { name: name(streak.holder), n: streak.length },
    });
  }

  if (a.shotAccuracy !== null && b.shotAccuracy !== null && a.wins !== b.wins) {
    const fewer: PlayerKey = a.wins < b.wins ? "a" : "b";
    const other: PlayerKey = fewer === "a" ? "b" : "a";
    if (summary[fewer].shotAccuracy! > summary[other].shotAccuracy!) {
      out.push({
        id: "accuracy",
        tone: fewer,
        key: "ins.accuracy",
        params: { name: name(fewer), x: fmt(summary[fewer].shotAccuracy!), y: fmt(summary[other].shotAccuracy!) },
      });
    }
  }

  const possA = a.possession.average;
  const possB = b.possession.average;
  if (possA !== null && possB !== null && Math.abs(possA - possB) >= 2 && a.wins !== b.wins) {
    const moreBall: PlayerKey = possA > possB ? "a" : "b";
    const moreWins: PlayerKey = a.wins > b.wins ? "a" : "b";
    if (moreBall !== moreWins) {
      out.push({
        id: "possession",
        tone: moreBall,
        key: "ins.possession",
        params: { a: name(moreBall), x: fmt(summary[moreBall].possession.average!), b: name(moreWins) },
      });
    }
  }

  if (a.cleanSheets !== b.cleanSheets) {
    const k: PlayerKey = a.cleanSheets > b.cleanSheets ? "a" : "b";
    out.push({
      id: "clean-sheets",
      tone: k,
      key: "ins.cleanSheets",
      params: { name: name(k), n: summary[k].cleanSheets, m: summary[k === "a" ? "b" : "a"].cleanSheets },
    });
  }

  if (a.avgGoalsFor !== null && b.avgGoalsFor !== null && a.avgGoalsFor !== b.avgGoalsFor) {
    const k: PlayerKey = a.avgGoalsFor > b.avgGoalsFor ? "a" : "b";
    out.push({
      id: "goals",
      tone: k,
      key: "ins.goals",
      params: { name: name(k), x: fmt(summary[k].avgGoalsFor!) },
    });
  }

  return out;
}
